"""Extract SEC 10-Q statement line items with duration awareness.

SEC EDGAR (companyfacts) is authoritative for reported financial statements.
Cash-flow and income-statement standalone quarters may be derived from
comparable year-to-date amounts. Balance-sheet amounts are never manufactured
by subtracting consecutive statements — they are point-in-time.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Any

